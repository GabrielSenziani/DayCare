    private void jButtonSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSalvarActionPerformed
        String nome = jTextFieldNome.getText().trim();
        String especie = jTextFieldEspecie.getText().trim();
        String raca = jTextFieldRaca.getText().trim();
        String dataStr = jFormattedTextFieldDataNascimento.getText().trim();

        if (nome.isEmpty() || especie.isEmpty() || dataStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nome, Espécie e Data de Nascimento são obrigatórios.", "Validação", JOptionPane.WARNING_MESSAGE);
            return;
        }

        LocalDate dataNascimento;
        try {
            dataNascimento = LocalDate.parse(dataStr, FORMATTER);
        } catch (DateTimeParseException ex) {
            JOptionPane.showMessageDialog(this, "Data inválida. Use o formato dd/MM/yyyy.", "Validação", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (jComboBoxClienteId.getSelectedIndex() < 0) {
            JOptionPane.showMessageDialog(this, "Selecione um cliente responsável.", "Validação", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Cliente clienteSelecionado = clientesCache.get(jComboBoxClienteId.getSelectedIndex());
        int clienteId = clienteSelecionado.getId();

        Animal animal;
        if (animalEmEdicaoId > 0) {
            animal = new Animal(animalEmEdicaoId, nome, especie, raca, dataNascimento, clienteId);
        } else {
            animal = new Animal(nome, especie, raca, dataNascimento, clienteId);
        }

        try {
            if (animalEmEdicaoId > 0) {
                animalService.atualizar(animal);
                JOptionPane.showMessageDialog(this, "Animal atualizado com sucesso!");
            } else {
                animalService.cadastrar(animal);
                JOptionPane.showMessageDialog(this, "Animal cadastrado com sucesso!");
            }
            limparCampos();
            carregarTabela();
        } catch (BusinessException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Erro de negócio", JOptionPane.WARNING_MESSAGE);
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Erro ao salvar animal: " + ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
            logger.severe("Erro ao salvar animal: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButtonSalvarActionPerformed

    private void carregarClientesCombo() {
        jComboBoxClienteId.removeAllItems();
        clientesCache.clear();
        try {
            List<Cliente> clientes = clienteService.listarTodos();
            for (Cliente c : clientes) {
                clientesCache.add(c);
                jComboBoxClienteId.addItem(c.getId() + " - " + c.getNome());
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar clientes: " + ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
            logger.severe("Erro ao carregar combo de clientes: " + ex.getMessage());
        }
    }

    private void carregarTabela() {
        DefaultTableModel model = (DefaultTableModel) jTableAnimais.getModel();
        model.setRowCount(0);
        animaisCache.clear();
        try {
            List<Animal> animais = animalService.listarTodos();
            for (Animal a : animais) {
                animaisCache.add(a);
                model.addRow(new Object[]{
                    a.getId(), a.getNome(), a.getEspecie(), a.getRaca(),
                    a.getDataNascimento().format(FORMATTER), a.getClienteId()
                });
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar animais: " + ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
            logger.severe("Erro ao carregar tabela de animais: " + ex.getMessage());
        }
    }

    private void limparCampos() {
        jTextFieldNome.setText("");
        jTextFieldEspecie.setText("");
        jTextFieldRaca.setText("");
        jFormattedTextFieldDataNascimento.setText("");
        if (jComboBoxClienteId.getItemCount() > 0) {
            jComboBoxClienteId.setSelectedIndex(0);
        }
        animalEmEdicaoId = 0;
        jTableAnimais.clearSelection();
        jTextFieldNome.requestFocus();
    }

