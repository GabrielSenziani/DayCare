    private void jButtonExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonExcluirActionPerformed
        int linha = jTableAnimais.getSelectedRow();
        if (linha < 0) {
            JOptionPane.showMessageDialog(this, "Selecione um animal na tabela para excluir.", "Atenção", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int id = animaisCache.get(linha).getId();
        String nome = animaisCache.get(linha).getNome();

        int confirm = JOptionPane.showConfirmDialog(this,
                "Deseja realmente excluir o animal: " + nome + "?",
                "Confirmar exclusão",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE);

        if (confirm == JOptionPane.YES_OPTION) {
            try {
                animalService.excluir(id);
                JOptionPane.showMessageDialog(this, "Animal excluído com sucesso!");
                limparCampos();
                carregarTabela();
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, "Erro ao excluir animal: " + ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
                logger.severe("Erro ao excluir animal: " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_jButtonExcluirActionPerformed

    private void jButtonEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditarActionPerformed
        int linha = jTableAnimais.getSelectedRow();
        if (linha < 0) {
            JOptionPane.showMessageDialog(this, "Selecione um animal na tabela para editar.", "Atenção", JOptionPane.WARNING_MESSAGE);
            return;
        }

        animalEmEdicaoId = animaisCache.get(linha).getId();
        Animal animal = animaisCache.get(linha);
        jTextFieldNome.setText(animal.getNome());
        jTextFieldEspecie.setText(animal.getEspecie());
        jTextFieldRaca.setText(animal.getRaca());
        jFormattedTextFieldDataNascimento.setText(animal.getDataNascimento().format(FORMATTER));

        for (int i = 0; i < clientesCache.size(); i++) {
            if (clientesCache.get(i).getId() == animal.getClienteId()) {
                jComboBoxClienteId.setSelectedIndex(i);
                break;
            }
        }

        jTextFieldNome.requestFocus();
    }//GEN-LAST:event_jButtonEditarActionPerformed

