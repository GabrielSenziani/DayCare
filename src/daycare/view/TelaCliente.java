    private void jButtonSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSalvarActionPerformed
        String cpf = jTextFieldCpf.getText().trim();
        String nome = jTextFieldNome.getText().trim();
        String telefone = jTextFieldTelefone.getText().trim();
        String email = jTextFieldEmail.getText().trim();
        String endereco = jTextFieldEndereco.getText().trim();

        if (cpf.isEmpty() || nome.isEmpty()) {
            JOptionPane.showMessageDialog(this, "CPF e Nome são obrigatórios.", "Validação", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String cpfDigitos = cpf.replaceAll("\\D", "");
        if (cpfDigitos.length() != 11) {
            JOptionPane.showMessageDialog(this, "O CPF deve estar completo no formato 000.000.000-00.", "Validação", JOptionPane.WARNING_MESSAGE);
            jTextFieldCpf.requestFocus();
            return;
        }

        if (!email.isEmpty() && !email.matches("^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$")) {
            JOptionPane.showMessageDialog(this, "Informe um e-mail válido contendo @ e domínio (ex: nome@email.com).", "Validação", JOptionPane.WARNING_MESSAGE);
            jTextFieldEmail.requestFocus();
            return;
        }

        Cliente cliente;
        if (clienteEmEdicaoId > 0) {
            cliente = new Cliente(clienteEmEdicaoId, cpf, nome, telefone, email, endereco);
        } else {
            cliente = new Cliente(cpf, nome, telefone, email, endereco);
        }

        try {
            if (clienteEmEdicaoId > 0) {
                clienteService.atualizar(cliente);
                JOptionPane.showMessageDialog(this, "Cliente atualizado com sucesso!");
            } else {
                clienteService.cadastrar(cliente);
                JOptionPane.showMessageDialog(this, "Cliente cadastrado com sucesso!");
            }
            limparCampos();
            carregarTabela();
        } catch (BusinessException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Erro de negócio", JOptionPane.WARNING_MESSAGE);
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Erro ao salvar cliente: " + ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
            logger.severe("Erro ao salvar: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButtonSalvarActionPerformed

