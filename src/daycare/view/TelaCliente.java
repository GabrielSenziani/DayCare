    private void carregarTabela() {
        DefaultTableModel model = (DefaultTableModel) jTableClientes.getModel();
        model.setRowCount(0);
        clientesCache.clear();
        try {
            List<Cliente> clientes = clienteService.listarTodos();
            for (Cliente c : clientes) {
                clientesCache.add(c);
                model.addRow(new Object[]{
                    c.getNome(), c.getCpf(), c.getTelefone(), c.getEmail(), c.getEndereco()
                });
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar clientes: " + ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
            logger.severe("Erro ao carregar tabela: " + ex.getMessage());
        }
    }

    private void limparCampos() {
        jTextFieldNome.setText("");
        jTextFieldCpf.setText("");
        jTextFieldTelefone.setText("");
        jTextFieldEmail.setText("");
        jTextFieldEndereco.setText("");
        clienteEmEdicaoId = 0;
        jTableClientes.clearSelection();
        jTextFieldNome.requestFocus();
    }

